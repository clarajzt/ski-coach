const DICT = { en, zh };
let lang = 'en';

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('ski.lang'); } catch { /* storage unavailable */ }
  lang = saved || ((navigator.language || 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en');
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  return lang;
}
export function setLang(l) {
  lang = l === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem('ski.lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}
export const getLang = () => lang;

/** Translate a key, filling {placeholders}. */
export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}
/** Pick the current language from an {en, zh} object. */
export const pick = (o) => (o ? o[lang] ?? o.en : '');
